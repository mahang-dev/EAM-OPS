export function tone(s: string) {
  return ["FAULT", "CRITICAL", "ABNORMAL"].includes(s)
    ? "danger"
    : ["PENDING", "ASSIGNED", "WAITING_REVIEW", "WARNING", "OPEN"].includes(s)
      ? "warning"
      : ["RUNNING", "CLOSED", "COMPLETED", "APPROVED", "RECOVERED"].includes(s)
        ? "success"
        : "info";
}
